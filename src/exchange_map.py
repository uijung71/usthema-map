def get_google_finance_url(ticker, is_etf=False):
    """Get working Google Finance URL for a ticker."""
    mapped = GOOGLE_FINANCE_MAP.get(ticker)
    if mapped:
        sym = mapped['symbol']
        exc = mapped['exchange']
        return f"https://www.google.com/finance/quote/{sym}:{exc}?hl=ko"
        
    # Safe fallback heuristics
    if ticker == 'SK하이닉스':
        return "https://www.google.com/finance/quote/000660:KRX?hl=ko"
    elif ticker == '삼성바이오로직스':
        return "https://www.google.com/finance/quote/207940:KRX?hl=ko"
    elif ticker == 'TSMC':
        return "https://www.google.com/finance/quote/TSM:NYSE?hl=ko"
    elif ticker == 'BYDDY':
        return "https://www.google.com/finance/quote/BYDDY:OTCMKTS?hl=ko"
        
    exc = "NYSEARCA" if is_etf else "NASDAQ"
    return f"https://www.google.com/finance/quote/{ticker}:{exc}?hl=ko"
